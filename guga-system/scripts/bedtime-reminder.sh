#!/usr/bin/env bash
# 洗漱 / 睡觉提醒 —— no_agent 任务，stdout 原样发送
# 2026-10-24 主人定：周日至周四 23:00 睡；周五晚不管；周六晚放宽到 12 点前。
# cron 排的是 0 23 * * 0,1,2,3,4,6（周五不跑）。
dow=$(date +%u)   # 1=周一 … 6=周六 7=周日
if [ "$dow" = "6" ]; then
  printf '🌙 今晚可以宽一点，12 点前收工就行。先去洗漱吧～\n'
else
  printf '🛁 该洗漱啦，准备睡觉了。今天辛苦啦，早点休息～ 晚安 🌙\n'
fi
