#!/usr/bin/env python3
"""把 ~/stack/remote/hosts.json 生成到 ~/.ssh/config.d/guga-remote。

只处理自有机器（kind == "own"）。guest 机器按设计一律不落盘，故不在此文件里，
也不生成别名。

用法：python3 gen-config.py
"""
import json
import os
import sys

HOME = os.path.expanduser("~")
HOSTS = os.path.join(HOME, "stack", "remote", "hosts.json")
OUT = os.path.join(HOME, ".ssh", "config.d", "guga-remote")

HEADER = "# GENERATED by gen-config.py from ~/stack/remote/hosts.json — DO NOT EDIT\n"


def render(hosts):
    lines = [HEADER]
    for alias, h in sorted(hosts.items()):
        if h.get("kind") != "own":
            continue  # guest 不落盘、不生成别名
        if h.get("via") == "reverse":
            hostname = "127.0.0.1"
            port = str(h.get("listen_port", 22022))
        else:  # direct
            hostname = h["host"]
            port = str(h.get("port", 22))
        identity = h.get("ops_identity", "guga_ops")
        lines.append(f"Host {alias}")
        lines.append(f"  HostName {hostname}")
        lines.append(f"  Port {port}")
        lines.append(f"  User {h.get('user', 'root')}")
        lines.append(f"  IdentityFile ~/.ssh/{identity}")
        lines.append("  IdentitiesOnly yes")
        lines.append("")
    return "\n".join(lines)


def main():
    if not os.path.exists(HOSTS):
        sys.exit(f"missing {HOSTS}")
    with open(HOSTS) as f:
        hosts = json.load(f)
    text = render(hosts)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text)
    print(f"wrote {OUT} ({len(hosts)} hosts)")


if __name__ == "__main__":
    main()
